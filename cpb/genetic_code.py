"""Standard genetic code tables."""

from collections import defaultdict

# Standard genetic code (DNA, T not U)
GENETIC_CODE: dict[str, str] = {
    "TTT": "F", "TTC": "F",
    "TTA": "L", "TTG": "L",
    "CTT": "L", "CTC": "L", "CTA": "L", "CTG": "L",
    "ATT": "I", "ATC": "I", "ATA": "I",
    "ATG": "M",
    "GTT": "V", "GTC": "V", "GTA": "V", "GTG": "V",
    "TCT": "S", "TCC": "S", "TCA": "S", "TCG": "S",
    "CCT": "P", "CCC": "P", "CCA": "P", "CCG": "P",
    "ACT": "T", "ACC": "T", "ACA": "T", "ACG": "T",
    "GCT": "A", "GCC": "A", "GCA": "A", "GCG": "A",
    "TAT": "Y", "TAC": "Y",
    "TAA": "*", "TAG": "*", "TGA": "*",
    "CAT": "H", "CAC": "H",
    "CAA": "Q", "CAG": "Q",
    "AAT": "N", "AAC": "N",
    "AAA": "K", "AAG": "K",
    "GAT": "D", "GAC": "D",
    "GAA": "E", "GAG": "E",
    "TGT": "C", "TGC": "C",
    "TGG": "W",
    "CGT": "R", "CGC": "R", "CGA": "R", "CGG": "R",
    "AGT": "S", "AGC": "S",
    "AGA": "R", "AGG": "R",
    "GGT": "G", "GGC": "G", "GGA": "G", "GGG": "G",
}

# Sorted list of all 64 codons
ALL_CODONS: list[str] = sorted(GENETIC_CODE.keys())

# Map amino acid → list of synonymous codons
_aa_to_codons: dict[str, list[str]] = defaultdict(list)
for _codon, _aa in GENETIC_CODE.items():
    _aa_to_codons[_aa].append(_codon)

AMINO_ACID_TO_CODONS: dict[str, list[str]] = {
    aa: sorted(codons) for aa, codons in sorted(_aa_to_codons.items())
}
